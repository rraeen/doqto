/**
 * A profile page for an example doctor, so the demo's search cards open something. Real doctors
 * come from the API; this exists only for demo and local builds.
 */
export function sampleProfileBySlug(slug: string): DoctorProfile | null {
  const d = SAMPLE_DOCTORS.find((x) => x.id === slug || x.slug === slug);
  if (!d) return null;
  const clinic = d.primaryClinic;
  return {
    id: d.id,
    slug: d.slug,
    name: d.name,
    gender: null,
    photoUrl: null,
    bio: `${d.name} has practised in ${d.city} for ${d.experienceYears ?? 'several'} years.`,
    languages: ['Hindi', 'English'],
    qualifications: [{ degree: 'MBBS' }],
    specialties: d.specialties,
    experienceYears: d.experienceYears,
    verificationStatus: 'verified',
    city: d.city,
    consultFee: d.consultFee,
    bookingFee: 1500,
    clinics: clinic
      ? [
          {
            id: clinic.id,
            name: clinic.name,
            phone: null,
            address: {
              line1: clinic.area ?? clinic.name,
              area: clinic.area ?? undefined,
              city: d.city,
              state: 'Uttar Pradesh',
              pincode: '243001',
            },
            location: null,
            photoUrls: [],
            timezone: 'Asia/Kolkata',
            mapsUrl: null,
          },
        ]
      : [],
    ratingSummary: d.ratingSummary,
    todayStatus: null,
  };
}
